function dump(list, heading) {
out.push('');
out.push('### ' + heading);
for (const e of list) {
out.push('');
out.push('#### ' + e.id + ' ' + e.title);
out.push('');
out.push('- 场景归属：' + e.scene + (e.account? '｜先查后答：' + e.account: ''));
if (e.questions && e.questions.length) out.push('- 口语问法集：' + e.questions.join('／'));
out.push('- 操作入口：' + (e.entry || '（无）'));
out.push('');
out.push('**正式版**');
out.push('');
out.push(e.formal);
out.push('');
out.push('**大白话版**');
out.push('');
out.push(e.plain);
}
}
